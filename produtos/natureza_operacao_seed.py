def seed_naturezas_for_empresa(empresa):
    """Cria as naturezas de operação padrão para uma empresa (idempotente)."""
    existing = set(
        NaturezaOperacao.objects.filter(empresa=empresa).values_list('codigo', flat=True)
    )
    bulk = [
        NaturezaOperacao(
            empresa=empresa,
            codigo=n['codigo'],
            descricao=n['descricao'],
            tipo=n['tipo'],
            observacoes=n.get('observacoes', ''),
            ativo=True,
        )
        for n in DEFAULT_NATUREZAS
        if n['codigo'] not in existing
    ]
    if bulk:
        NaturezaOperacao.objects.bulk_create(bulk)
    return len(bulk)
