def seed_defensivos_for_empresa(empresa):
    """
    Cria os defensivos pré-configurados para uma empresa.
    
    Idempotente: Se defender já existe, ignora (não duplica).
    
    Args:
        empresa: Instância de Empresa
        
    Returns:
        tuple: (quantidade_criada, quantidade_ignorada)
    """
    from produtos.models import Produto
    
    criados = 0
    ignorados = 0
    
    for defensivo in DEFENSIVOS_SEED:
        # Tenta criar, se já existe ignora
        produto, created = Produto.objects.get_or_create(
            empresa=empresa,
            nome=defensivo['nome_comercial'],
            defaults={
                'categoria_agricola': 'DEFENSIVO',
                'classe_agronomica': defensivo['classe_agronomica'],
                'classe_toxicologica': defensivo['classe_toxicologica'],
                'classe_ambiental': defensivo['classe_ambiental'],
                'modo_aplicacao': defensivo['modo_aplicacao'],
                'ingrediente_ativo': defensivo.get('ingrediente_ativo', ''),
                'empresa_fabricante': defensivo.get('empresa_fabricante', ''),
                'numero_registro_mapa': defensivo.get('numero_registro_mapa', ''),
                'ativo': defensivo.get('ativo', True),
                'tipo_produto': 'REVENDA',
                'tipo_item': '07',  # Material de Uso e Consumo
                'origem_mercadoria': '0',  # Nacional
            }
        )
        
        if created:
            criados += 1
        else:
            ignorados += 1
    
    return criados, ignorados


